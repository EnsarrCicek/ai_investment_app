"""MOBILE_SHADOW Flutter toplayıcısı için çalışma çapalarını FINAL prospective manifestten üretir (YALNIZ araştırma).

Evren elle yazılmaz: dondurulmuş manifest (`momentum_prospective_manifest.json`) SHA doğrulamasıyla okunur ve
`lib/features/research_collector/domain/study_anchors.g.dart` yeniden yazılır. Manifest DEĞİŞTİRİLMEZ.

Kullanım (backend klasöründen):
    .venv\\Scripts\\python.exe -X utf8 scripts\\generate_mobile_shadow_anchors.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.research.momentum_collector import manifest as mm  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "lib" / "features" / "research_collector" / "domain" / "study_anchors.g.dart"


def render(m: dict) -> str:
    c = m["config"]
    if c["manifest_status"] != mm.FINAL:
        raise SystemExit("manifest FINAL değil: mobil çapalar yalnız başlatılmış çalışmadan üretilir")
    universe = "\n".join(f"  '{s}'," for s in c["universe"])
    descriptive = ", ".join(f"'{s}'" for s in c["descriptive_only_symbols"])
    return f"""// GENERATED by backend/scripts/generate_mobile_shadow_anchors.py — DO NOT EDIT BY HAND.
// Source: backend/app/research/momentum_collector/momentum_prospective_manifest.json (FINAL, SHA-verified).

/// Prospective study manifest SHA-256 (FINAL).
const String kStudyManifestSha256 = '{m["sha256"]}';

/// MOMENTUM_EVENT_LABEL_V2 FINAL manifest SHA-256.
const String kLabelManifestSha256 = '{c["label_manifest_sha256"]}';

/// SHA-256 of the canonical JSON of the sorted primary universe.
const String kUniverseSha256 = '{c["universe_sha256"]}';

const String kStudyVersion = '{c["study_version"]}';
const String kProspectiveStartSession = '{c["prospective_start_session"]}';
const String kBenchmark = '{c["benchmark"]}';
const List<String> kDescriptiveOnlySymbols = [{descriptive}];
const String kConsumedFinalFirstDay = '{c["consumed_final_days_excluded"][0]}';
const String kConsumedFinalLastDay = '{c["consumed_final_days_excluded"][1]}';

/// Primary universe ({c["universe_count"]} assets), sorted, as frozen in the manifest.
const List<String> kPrimaryUniverse = [
{universe}
];
"""


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(mm.load()), encoding="utf-8", newline="\n")
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
